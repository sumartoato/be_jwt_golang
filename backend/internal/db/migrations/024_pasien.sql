-- Master Data Klinik > Pasien: patients (refmpasien) and the tables they refer
-- to. Same columns, types and primary keys as in the legacy "lab" database.
-- Data is loaded with scripts/import-lab-pasien.sh, not seeded here. Foreign
-- keys are added by 025_pasien_keys.sql once the lab data was checked.

-- ---------- Lookups ----------
-- In lab, refgender, refagama, refstatuskawin and refkelurahan have no primary
-- key; 025 adds them. (lab also has refkelurahanall, which patients do not use.)
CREATE TABLE IF NOT EXISTS refgender (
    id   integer GENERATED BY DEFAULT AS IDENTITY,
    info varchar(25)
);
CREATE TABLE IF NOT EXISTS refgoldarah (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    info varchar(15)
);
CREATE TABLE IF NOT EXISTS refagama (
    id   integer GENERATED BY DEFAULT AS IDENTITY,
    info varchar(25)
);
CREATE TABLE IF NOT EXISTS refstatuskawin (
    id   integer GENERATED BY DEFAULT AS IDENTITY,
    info varchar(25)
);
--   jamkestype, status_limit, limit  insurer settings from the legacy app
CREATE TABLE IF NOT EXISTS refjaminankesehatan (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama         varchar(100) NOT NULL,
    alamat       varchar(100),
    telp         varchar(15),
    fax          varchar(15),
    create_user  varchar(20),
    create_date  timestamp(3),
    update_user  varchar(20),
    update_date  timestamp(3),
    isactive     integer DEFAULT 1,
    jamkestype   integer,
    status_limit integer,
    "limit"      double precision
);

-- Region hierarchy: provinsi > kabupaten/kota > kecamatan > kelurahan.
CREATE TABLE IF NOT EXISTS refprovinsi (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    info varchar(50)
);
CREATE TABLE IF NOT EXISTS refkabupaten (
    id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    info    varchar(100),
    id_prov integer
);
CREATE TABLE IF NOT EXISTS refkecamatan (
    id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    info   varchar(100),
    id_kab integer
);
CREATE TABLE IF NOT EXISTS refkelurahan (
    id              integer GENERATED BY DEFAULT AS IDENTITY,
    info            varchar(100),
    id_kec          integer,
    kode_kemendagri varchar(20)
);

-- ---------- Patients ----------
--   no_rm                     medical record number
--   tgl_kun                   first visit date
--   penanggung                responsible person / parent
--   id_jamkes, no_jamkes      health insurer and card number
--   cabang                    refbranch.kode of the patient's branch
--   ihs_*, notesatusehat      Satu Sehat (IHS) patient link
CREATE TABLE IF NOT EXISTS refmpasien (
    id            integer GENERATED BY DEFAULT AS IDENTITY,
    no_rm         varchar(10) NOT NULL,
    nama          varchar(50) NOT NULL,
    tmpt_lahir    varchar(30),
    tgl_lahir     date,
    alamat        varchar(100),
    id_kel        integer,
    telp          varchar(20),
    hp            varchar(50),
    id_gender     integer,
    id_goldarah   integer,
    id_agama      integer,
    id_status_kwn integer,
    tgl_kun       date,
    penanggung    varchar(50),
    id_jamkes     integer,
    create_user   varchar(20),
    create_date   timestamp(3),
    update_user   varchar(20),
    update_date   timestamp(3),
    no_jamkes     varchar(100),
    cabang        varchar(10),
    nik           varchar(30),
    alergi        text,
    ihs_id        varchar(30),
    ihs_name      varchar(100),
    ihs_status    varchar(20),
    notesatusehat varchar(1),
    rt            varchar(4),
    rw            varchar(4),
    CONSTRAINT refmpasien_pkey PRIMARY KEY (id)
);

-- Indexes for server-side paging, sorting and searching over ~430k patients.
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE INDEX IF NOT EXISTS refmpasien_cabang_id_idx ON refmpasien (cabang, id);
CREATE INDEX IF NOT EXISTS refmpasien_nama_idx ON refmpasien (nama);
CREATE INDEX IF NOT EXISTS refmpasien_no_rm_idx ON refmpasien (no_rm);
CREATE INDEX IF NOT EXISTS refmpasien_nama_trgm ON refmpasien USING gin (nama gin_trgm_ops);
CREATE INDEX IF NOT EXISTS refmpasien_no_rm_trgm ON refmpasien USING gin (no_rm gin_trgm_ops);
CREATE INDEX IF NOT EXISTS refmpasien_nik_trgm ON refmpasien USING gin (nik gin_trgm_ops);
CREATE INDEX IF NOT EXISTS refmpasien_alamat_trgm ON refmpasien USING gin (alamat gin_trgm_ops);
