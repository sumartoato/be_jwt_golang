-- Which branches (refbranch.kode) each user belongs to. A user can be mapped to
-- several branches. Same columns, types and primary key as refbranchauth in the
-- legacy "lab" database, where userid is a username; here it holds users.id (a UUID).
CREATE TABLE IF NOT EXISTS refbranchauth (
    id     integer GENERATED BY DEFAULT AS IDENTITY,
    branch varchar(10),
    userid varchar(50),
    CONSTRAINT refbranchauth_pkey PRIMARY KEY (id)
);

-- Additions to the lab layout, so the mapping stays clean:
-- no duplicate pair (lab has one), and no unknown branch code.
ALTER TABLE refbranchauth ADD CONSTRAINT refbranchauth_branch_userid_key UNIQUE (branch, userid);
ALTER TABLE refbranchauth ADD CONSTRAINT fk_refbranchauth_branch
    FOREIGN KEY (branch) REFERENCES refbranch (kode) ON DELETE CASCADE;
CREATE INDEX IF NOT EXISTS refbranchauth_userid_idx ON refbranchauth (userid);
