-- Transaksi Klinik > Penerimaan Barang (legacy /GoodReceive): goods receipts
-- (trxfaktur), their drug lines (trxfakturobat), totals and payment
-- (trxfakturtotal), and the suppliers (refsupplier). Same columns and types as
-- in the legacy "lab" database. Data is loaded with
-- scripts/import-lab-penerimaan-barang.sh.

-- Suppliers; a receipt with id_supp 0 has none ("-").
CREATE TABLE IF NOT EXISTS refsupplier (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama        varchar(40),
    alamat      varchar(100),
    telp        varchar(15),
    fax         varchar(15),
    cp          varchar(40),
    telp_cp     varchar(15),
    create_user varchar(20),
    create_date timestamp(3),
    update_user varchar(20),
    update_date timestamp(3)
);

--   tgl             entry time (Tgl Trans, clinic time)
--   tgl_jtp         payment due date
--   no_fak          the supplier's invoice / delivery number (No GR)
--   tgl_fak         the receipt date (Tgl GR)
--   id_supp         refsupplier, 0 = none
--   id_jenis_byr    refjenisbayar
--   cabang          refbranch.kode of the receiving branch
--   id_distributor  refdistributorobat
CREATE TABLE IF NOT EXISTS trxfaktur (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tgl            timestamp(3),
    tgl_jtp        timestamp(3),
    no_fak         varchar(15),
    tgl_fak        timestamp(3),
    id_supp        integer,
    id_jenis_byr   integer,
    create_user    varchar(20),
    create_date    timestamp(3),
    update_user    varchar(20),
    update_date    timestamp(3),
    cabang         varchar(30),
    id_distributor integer
);
CREATE INDEX IF NOT EXISTS trxfaktur_cabang_tgl_idx ON trxfaktur (cabang, tgl DESC);

--   byk       quantity in the buying unit, tot_qjb the same in selling units
--   hbeli     buying price, disc the discount
--   no_batch / tgl_exp  batch number and expiry date
CREATE TABLE IF NOT EXISTS trxfakturobat (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_fak   integer NOT NULL REFERENCES trxfaktur (id) ON DELETE CASCADE,
    id_obat  integer,
    no_batch varchar(20),
    tgl_exp  date,
    disc     double precision,
    hbeli    double precision,
    byk      double precision,
    tot_qjb  double precision
);
CREATE INDEX IF NOT EXISTS trxfakturobat_id_fak_idx ON trxfakturobat (id_fak);

--   total, potongan (discount), cicilan (paid), utang (still owed)
--   no_close / tgl_close / status  settlement, as for sales
CREATE TABLE IF NOT EXISTS trxfakturtotal (
    id_fak    integer PRIMARY KEY REFERENCES trxfaktur (id) ON DELETE CASCADE,
    total     double precision,
    cicilan   double precision,
    potongan  double precision,
    utang     double precision,
    no_close  integer,
    tgl_close timestamp(3),
    status    integer
);
