-- Transaksi Klinik > Pengobatan: treatment sales (trxjual), their totals and
-- settlement status (trxjualtotal) and the payment types (refjenisbayar).
-- Same columns, types and primary keys as in the legacy "lab" database. Data is
-- loaded with scripts/import-lab-pengobatan.sh; 035 adds the keys.

-- TUNAI, HUTANG, JAMKES, KARTU KREDIT, DEBIT EDC, NON TUNAI, ...
CREATE TABLE IF NOT EXISTS refjenisbayar (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    info varchar(15),
    flag integer
);

--   tgl                 transaction time (clinic time)
--   no_kwi / tgl_kwi    receipt number and date (No Kuitansi)
--   id_pas              refmpasien
--   id_jenis_byr        refjenisbayar (Pembayaran)
--   id_kun              trxpendaftaran: the registration this treatment belongs to
--   id_jenis_rwt        refjenisrawat (Jenis Rawat)
--   id_dok              refmdokter
--   id_perujuk_otc      refperujukotc, for over-the-counter sales
--   id_jamkes, no_jamkes  refjaminankesehatan and the member number
--   flow_status         legacy workflow step
--   encounter*          SATUSEHAT encounter id, status and timestamps
CREATE TABLE IF NOT EXISTS trxjual (
    id                    integer GENERATED BY DEFAULT AS IDENTITY,
    tgl                   timestamp(3),
    no_kwi                varchar(11),
    tgl_kwi               date,
    id_pas                integer,
    id_jenis_byr          integer,
    id_kun                integer,
    id_jenis_rwt          integer,
    id_dok                integer,
    create_user           varchar(20),
    create_date           timestamp(3),
    update_user           varchar(20),
    update_date           timestamp(3),
    id_perujuk_otc        integer,
    id_jamkes             integer,
    no_jamkes             varchar(100),
    cabang                varchar(10),
    flow_status           varchar(30),
    encounterid           varchar(100),
    encounterstatus       varchar(20),
    encountercreateddate  timestamp(3),
    encounterupdatedate   timestamp(3),
    encounterfinisheddate timestamp(3),
    CONSTRAINT trxjual_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS trxjual_cabang_tgl_idx ON trxjual (cabang, tgl DESC);
CREATE INDEX IF NOT EXISTS trxjual_tgl_idx ON trxjual (tgl DESC);
CREATE INDEX IF NOT EXISTS trxjual_id_pas_idx ON trxjual (id_pas);
CREATE INDEX IF NOT EXISTS trxjual_id_kun_idx ON trxjual (id_kun);

-- One row per sale.
--   tot_obat, tot_tndk, tot_pnjng  drugs, procedures and examinations
--   total                          amount due (Total)
--   status                         1 = Close (paid), 2 = Cancel, otherwise Open
--   cancelby, cancelat, cancelreason  set when a sale is cancelled
CREATE TABLE IF NOT EXISTS trxjualtotal (
    id_jual      integer NOT NULL,
    tot_obat     double precision,
    tot_tndk     double precision,
    tot_pnjng    double precision,
    total        double precision,
    cicilan      double precision,
    potongan     double precision,
    piutang      double precision,
    no_close     integer,
    tgl_close    date,
    status       integer,
    point        double precision,
    pembayaran   double precision,
    cancelby     varchar(30),
    cancelat     timestamp(3),
    cancelreason varchar(100),
    CONSTRAINT trxjualtotal_pkey PRIMARY KEY (id_jual)
);
