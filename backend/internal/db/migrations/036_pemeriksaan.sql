-- Examination notes per registration (trxpemeriksaan): the nurse's and doctor's
-- findings, and the responsible doctor (id_dok, "Dokter PJ"). Same columns,
-- types and primary key as in the legacy "lab" database; loaded with
-- scripts/import-lab-pemeriksaan.sh.
--
-- id_kun is unique in lab (one examination per registration). There are no
-- foreign keys to trxpendaftaran or refmdokter, because the Pendaftaran and
-- Dokter re-imports truncate those tables with CASCADE.
--   id_kun            trxpendaftaran
--   id_dok            refmdokter: the responsible doctor (Dokter PJ)
--   tekanan_darah_*   blood pressure (mmHg); berat_badan kg; tinggi_badan cm; suhu °C
CREATE TABLE IF NOT EXISTS trxpemeriksaan (
    id                                integer GENERATED BY DEFAULT AS IDENTITY,
    id_kun                            integer,
    keluhan_utama                     varchar(300),
    anamnesis                         varchar(300),
    tekanan_darah_sistole             integer,
    tekanan_darah_diastole            integer,
    berat_badan                       integer,
    tinggi_badan                      integer,
    pemeriksaanfisik                  varchar(300),
    rekap_hasil_pemeriksaan_penunjang varchar(300),
    hasil_pemeriksaan_penunjang       varchar(300),
    rencana_penatalaksanaan           varchar(300),
    create_user                       varchar(20),
    create_date                       timestamp(3),
    update_user                       varchar(20),
    update_date                       timestamp(3),
    suhu                              double precision,
    id_dok                            integer,
    hasil_pemeriksaan_dokter          varchar(400),
    tindakan_dokter                   varchar(400),
    CONSTRAINT trxpemeriksaan_pkey PRIMARY KEY (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS trxpemeriksaan_id_kun_key ON trxpemeriksaan (id_kun);
