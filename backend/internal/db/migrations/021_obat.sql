-- Master Data Klinik > Obat: drugs (refobat), their lookups, and stock/prices
-- per branch (trxstock). Same columns, types and primary keys as in the legacy
-- "lab" database. Data is loaded with scripts/import-lab-obat.sh, not seeded here.

-- ---------- Lookups ----------
CREATE TABLE IF NOT EXISTS refjenisobat (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    info     varchar(25),
    sts_hmlm integer
);
CREATE TABLE IF NOT EXISTS refsatuan (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    info varchar(15)
);
CREATE TABLE IF NOT EXISTS reflogoobat (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    info varchar(15)
);
CREATE TABLE IF NOT EXISTS refprodusen (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama        varchar(40),
    alamat      varchar(100),
    telp        varchar(15),
    fax         varchar(15),
    create_user varchar(20),
    create_date timestamp(3),
    update_user varchar(20),
    update_date timestamp(3)
);
CREATE TABLE IF NOT EXISTS refkodemovingobat (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kodemoving varchar(10)
);
CREATE TABLE IF NOT EXISTS refkodemovingpo (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kodemovingpo varchar(10)
);
CREATE TABLE IF NOT EXISTS refdistributorobat (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    distributor varchar(300),
    alamat      varchar(200),
    telp        varchar(15),
    fax         varchar(25),
    cp          varchar(40),
    telp_cp     varchar(25),
    create_user varchar(20),
    create_date timestamp(3),
    update_user varchar(20),
    update_date timestamp(3)
);
CREATE TABLE IF NOT EXISTS refprincipalobat (
    id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    principal varchar(300)
);
CREATE TABLE IF NOT EXISTS refgolonganobat (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    golonganobat varchar(300)
);

-- ---------- Drugs ----------
--   isi, isi_per_box   content per unit / per box (free text)
--   sat_beli, sat_jual purchase and sale unit (refsatuan)
--   qjb                quantity conversion between the two units
--   hbeli, hjual, hp   default purchase, sale and cost price (per branch: trxstock)
--   non_aktif          1 = inactive drug
--   kena_pajak         1 = taxable
CREATE TABLE IF NOT EXISTS refobat (
    id               integer GENERATED BY DEFAULT AS IDENTITY,
    nama             varchar(100) NOT NULL,
    isi              varchar(10),
    id_jenis         integer,
    id_logo          integer,
    id_prod          integer,
    sat_beli         integer,
    sat_jual         integer,
    qjb              double precision,
    hbeli            double precision,
    hjual            double precision,
    hp               double precision,
    non_aktif        integer,
    create_user      varchar(20),
    create_date      timestamp(3),
    update_user      varchar(20),
    update_date      timestamp(3),
    id_moving        integer,
    id_distributor   integer,
    id_principal     integer,
    id_golongan_obat integer,
    komposisi        text,
    id_moving_po     integer,
    kena_pajak       integer NOT NULL DEFAULT 0,
    isi_per_box      varchar(20),
    CONSTRAINT refobat_pkey PRIMARY KEY (id)
);

-- Additions to the lab layout. Every lookup reference in lab is valid except
-- id_prod (most point to producers that no longer exist), so id_prod has no FK.
ALTER TABLE refobat
    ADD CONSTRAINT fk_refobat_jenis       FOREIGN KEY (id_jenis)         REFERENCES refjenisobat (id),
    ADD CONSTRAINT fk_refobat_logo        FOREIGN KEY (id_logo)          REFERENCES reflogoobat (id),
    ADD CONSTRAINT fk_refobat_sat_beli    FOREIGN KEY (sat_beli)         REFERENCES refsatuan (id),
    ADD CONSTRAINT fk_refobat_sat_jual    FOREIGN KEY (sat_jual)         REFERENCES refsatuan (id),
    ADD CONSTRAINT fk_refobat_moving      FOREIGN KEY (id_moving)        REFERENCES refkodemovingobat (id),
    ADD CONSTRAINT fk_refobat_moving_po   FOREIGN KEY (id_moving_po)     REFERENCES refkodemovingpo (id),
    ADD CONSTRAINT fk_refobat_distributor FOREIGN KEY (id_distributor)   REFERENCES refdistributorobat (id),
    ADD CONSTRAINT fk_refobat_principal   FOREIGN KEY (id_principal)     REFERENCES refprincipalobat (id),
    ADD CONSTRAINT fk_refobat_golongan    FOREIGN KEY (id_golongan_obat) REFERENCES refgolonganobat (id);

-- ---------- Stock and prices per branch ----------
--   cabang    refbranch.kode
--   stok, stok_min, hbeli, hp, hjual  for this drug at this branch
--   isactive  1 = sold at this branch
CREATE TABLE IF NOT EXISTS trxstock (
    id_obat  integer NOT NULL,
    stok     double precision,
    stok_min double precision,
    cabang   varchar(20) NOT NULL,
    hbeli    double precision,
    hp       double precision,
    hjual    double precision,
    isactive integer NOT NULL DEFAULT 1,
    CONSTRAINT pk_trxstock PRIMARY KEY (id_obat, cabang)
);

-- Additions: lab has stock rows for drugs that were deleted; they are not imported.
ALTER TABLE trxstock
    ADD CONSTRAINT fk_trxstock_obat   FOREIGN KEY (id_obat) REFERENCES refobat (id) ON DELETE CASCADE,
    ADD CONSTRAINT fk_trxstock_cabang FOREIGN KEY (cabang)  REFERENCES refbranch (kode);
CREATE INDEX IF NOT EXISTS trxstock_cabang_idx ON trxstock (cabang);
