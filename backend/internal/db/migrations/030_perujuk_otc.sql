-- Master Data Klinik > Penjual OTC: the people who refer over-the-counter
-- sales ("Perujuk OTC"; trxjual.id_perujuk_otc in lab points here). Same
-- columns, types and primary key as in the legacy "lab" database. Data is
-- loaded with scripts/import-lab-perujuk-otc.sh. Names are not unique in lab
-- (one name appears twice), so there is no unique constraint.
CREATE TABLE IF NOT EXISTS refperujukotc (
    id   integer GENERATED BY DEFAULT AS IDENTITY,
    nama varchar(50),
    CONSTRAINT refperujukotc_pkey PRIMARY KEY (id)
);
