-- Reshape "branches" (018) into "refbranch" with the same columns, types and
-- primary key as refbranch in the existing "lab" database, keeping any rows.
--
--   kode            branch code, primary key; cannot be changed after creation
--   nama            branch name
--   alamat, telp    address and phone
--   isactive        1 active, 0 inactive
--   kode_kwt        kode KWT (may differ from kode, e.g. MED uses BTA)
--   npwp, nama_npwp tax number and the name registered with it
--   db_hbee         name of the branch's HBee database
--   kode_fasyankes,
--   nama_fasyankes  the facility as registered at the Ministry of Health
--   clientkey,
--   secretkey       Satu Sehat OAuth credentials. The API never returns secretkey
--   organizationid  Satu Sehat Organization ID
--   isinternal      1 own clinic, 0 partner/external
ALTER TABLE branches RENAME TO refbranch;

ALTER TABLE refbranch DROP CONSTRAINT branches_pkey;
ALTER TABLE refbranch DROP CONSTRAINT branches_code_key;
ALTER TABLE refbranch DROP COLUMN created_at;
ALTER TABLE refbranch DROP COLUMN updated_at;

ALTER TABLE refbranch RENAME COLUMN code TO kode;
ALTER TABLE refbranch RENAME COLUMN name TO nama;
ALTER TABLE refbranch RENAME COLUMN fasyankes_code TO kode_fasyankes;
ALTER TABLE refbranch RENAME COLUMN fasyankes_name TO nama_fasyankes;
ALTER TABLE refbranch RENAME COLUMN client_key TO clientkey;
ALTER TABLE refbranch RENAME COLUMN secret_key TO secretkey;
ALTER TABLE refbranch RENAME COLUMN organization_id TO organizationid;
ALTER TABLE refbranch RENAME COLUMN is_active TO isactive;

ALTER TABLE refbranch
    ALTER COLUMN kode           TYPE varchar(20),
    ALTER COLUMN nama           TYPE varchar(50),
    ALTER COLUMN nama           DROP NOT NULL,
    ALTER COLUMN kode_fasyankes TYPE varchar(50),
    ALTER COLUMN kode_fasyankes DROP NOT NULL,
    ALTER COLUMN kode_fasyankes DROP DEFAULT,
    ALTER COLUMN nama_fasyankes TYPE varchar(100),
    ALTER COLUMN nama_fasyankes DROP NOT NULL,
    ALTER COLUMN nama_fasyankes DROP DEFAULT,
    ALTER COLUMN clientkey      TYPE varchar(100),
    ALTER COLUMN clientkey      DROP NOT NULL,
    ALTER COLUMN clientkey      DROP DEFAULT,
    ALTER COLUMN secretkey      TYPE varchar(100),
    ALTER COLUMN secretkey      DROP NOT NULL,
    ALTER COLUMN secretkey      DROP DEFAULT,
    ALTER COLUMN organizationid TYPE varchar(100),
    ALTER COLUMN organizationid DROP NOT NULL,
    ALTER COLUMN organizationid DROP DEFAULT,
    ALTER COLUMN db_hbee        TYPE varchar(50),
    ALTER COLUMN db_hbee        DROP NOT NULL,
    ALTER COLUMN db_hbee        DROP DEFAULT,
    ALTER COLUMN isactive       DROP NOT NULL,
    ALTER COLUMN isactive       DROP DEFAULT;
ALTER TABLE refbranch ALTER COLUMN isactive TYPE integer USING CASE WHEN isactive THEN 1 ELSE 0 END;

ALTER TABLE refbranch
    ADD COLUMN alamat     varchar(200),
    ADD COLUMN telp       varchar(200),
    ADD COLUMN kode_kwt   varchar(10),
    ADD COLUMN npwp       varchar(50),
    ADD COLUMN nama_npwp  varchar(100),
    ADD COLUMN isinternal integer NOT NULL DEFAULT 0;

-- Empty strings become NULL, as in lab.
UPDATE refbranch SET
    kode_fasyankes = NULLIF(kode_fasyankes, ''),
    nama_fasyankes = NULLIF(nama_fasyankes, ''),
    clientkey      = NULLIF(clientkey, ''),
    secretkey      = NULLIF(secretkey, ''),
    organizationid = NULLIF(organizationid, ''),
    db_hbee        = NULLIF(db_hbee, '');

-- id: SERIAL -> identity, continuing after the current maximum.
ALTER TABLE refbranch ALTER COLUMN id DROP DEFAULT;
DROP SEQUENCE IF EXISTS branches_id_seq;
ALTER TABLE refbranch ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('refbranch', 'id'), COALESCE((SELECT max(id) FROM refbranch), 0) + 1, false);

ALTER TABLE refbranch ADD CONSTRAINT pk_refbranch PRIMARY KEY (kode);

