-- Front Office Klinik > Pendaftaran Pasien: patient visit registrations
-- (trxpendaftaran), the services they register for (refjenisrawat), the visit
-- status (refstatustransaksi) and the patients' point balance (refpasienpoint).
-- Same columns, types and primary keys as in the legacy "lab" database. Data is
-- loaded with scripts/import-lab-pendaftaran.sh; 032 adds the foreign keys.

--   ispemeriksaan  a doctor's examination (poli)
--   isactive       1 = offered in the registration form
--   neednoantrian  1 = gets a poli queue number, written firstcode + 3 digits (U001)
--   idnpwp         legacy tax-entity reference, kept as is
CREATE TABLE IF NOT EXISTS refjenisrawat (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    info          varchar(25),
    ispemeriksaan boolean DEFAULT false,
    isactive      integer NOT NULL DEFAULT 1,
    idnpwp        integer,
    neednoantrian integer NOT NULL DEFAULT 0,
    firstcode     varchar(1)
);

-- NON KUN, CLOSE, DAFTAR, PROSES, PAYMENT, CANCEL
CREATE TABLE IF NOT EXISTS refstatustransaksi (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    info varchar(15)
);

--   no_antri                     queue number per branch and day (1, 2, 3, ...)
--   no_antri_poli                queue number per branch, day and service
--   no_antri_poli_str            firstcode + 3 digits for services that need one (U015)
--   tgl_masuk / tgl_keluar       arrival / departure
--   id_pas                       refmpasien
--   id_jenis_rwt                 refjenisrawat (Pelayanan)
--   id_statustr                  refstatustransaksi (Status Kunjungan)
--   status_kartu                 1 = the patient used their card (Pakai Kartu)
--   cancelby, cancelat, cancelreason  set when a registration is cancelled
CREATE TABLE IF NOT EXISTS trxpendaftaran (
    id                integer GENERATED BY DEFAULT AS IDENTITY,
    no_antri          integer,
    tgl_masuk         timestamp(3),
    tgl_keluar        timestamp(3),
    id_pas            integer,
    id_jenis_rwt      integer,
    id_statustr       integer,
    create_user       varchar(20),
    create_date       timestamp(3),
    update_user       varchar(20),
    update_date       timestamp(3),
    cabang            varchar(10),
    status_kartu      integer,
    cancelby          varchar(30),
    cancelat          timestamp(3),
    cancelreason      varchar(100),
    no_antri_poli     integer,
    no_antri_poli_str varchar(4),
    CONSTRAINT trxpendaftaran_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS trxpendaftaran_cabang_tgl_idx ON trxpendaftaran (cabang, tgl_masuk DESC);
CREATE INDEX IF NOT EXISTS trxpendaftaran_tgl_idx ON trxpendaftaran (tgl_masuk DESC);
CREATE INDEX IF NOT EXISTS trxpendaftaran_id_pas_idx ON trxpendaftaran (id_pas);

-- A patient's current point balance ("Total Point").
CREATE TABLE IF NOT EXISTS refpasienpoint (
    id_pas integer NOT NULL,
    point  double precision,
    CONSTRAINT refpasienpoint_pkey PRIMARY KEY (id_pas)
);
