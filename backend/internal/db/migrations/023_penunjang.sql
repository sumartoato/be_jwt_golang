-- Master Data Klinik > Penunjang: supporting examinations (lab, radiology, ...)
-- in refpenunjang, their type, and prices per branch (refpenunjangdetail). Same
-- columns, types and primary keys as in the legacy "lab" database. Data is
-- loaded with scripts/import-lab-penunjang.sh, not seeded here.

-- The type table is called refjenispanjang in lab; the name is kept as is.
CREATE TABLE IF NOT EXISTS refjenispanjang (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    info varchar(15)
);

--   hjual, hjual_jamkes  default sale and health-insurance (jamkes) price
--   isactive             1 = active examination
CREATE TABLE IF NOT EXISTS refpenunjang (
    id           integer GENERATED BY DEFAULT AS IDENTITY,
    nama         varchar(100) NOT NULL,
    id_jenis     integer,
    hjual        double precision,
    create_user  varchar(20),
    create_date  timestamp(3),
    update_user  varchar(20),
    update_date  timestamp(3),
    isactive     integer DEFAULT 1,
    hjual_jamkes double precision,
    CONSTRAINT refpenunjang_pkey PRIMARY KEY (id)
);

--   cabang               refbranch.kode
--   hjual, hjual_jamkes  prices of the examination at this branch
--   isactive             1 = offered at this branch
CREATE TABLE IF NOT EXISTS refpenunjangdetail (
    id           integer GENERATED BY DEFAULT AS IDENTITY,
    id_penunjang integer,
    cabang       varchar(3),
    hjual        double precision,
    hjual_jamkes double precision,
    isactive     integer NOT NULL DEFAULT 1,
    CONSTRAINT refpenunjangdetail_pkey PRIMARY KEY (id)
);

-- Additions to the lab layout (the lab data satisfies all of them):
-- one price row per examination and branch, and no unknown type, examination or branch.
ALTER TABLE refpenunjang
    ADD CONSTRAINT fk_refpenunjang_jenis FOREIGN KEY (id_jenis) REFERENCES refjenispanjang (id);
ALTER TABLE refpenunjangdetail
    ADD CONSTRAINT refpenunjangdetail_penunjang_cabang_key UNIQUE (id_penunjang, cabang),
    ADD CONSTRAINT fk_refpenunjangdetail_penunjang FOREIGN KEY (id_penunjang) REFERENCES refpenunjang (id) ON DELETE CASCADE,
    ADD CONSTRAINT fk_refpenunjangdetail_cabang FOREIGN KEY (cabang) REFERENCES refbranch (kode);
CREATE INDEX IF NOT EXISTS refpenunjangdetail_cabang_idx ON refpenunjangdetail (cabang);
