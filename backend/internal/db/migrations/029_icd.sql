-- Master Data Klinik > ICD: ICD-X diagnosis codes (reficd) and their type
-- (refjenisicd: GIGI, THT, SARAF, ...). Same columns, types and primary keys as
-- in the legacy "lab" database. Data is loaded with scripts/import-lab-icd.sh.

CREATE TABLE IF NOT EXISTS refjenisicd (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    info varchar(15)
);

--   kode_icd      ICD-X code, e.g. K04.3
--   nama          disease name
--   id_jenis_icd  refjenisicd
CREATE TABLE IF NOT EXISTS reficd (
    id           integer GENERATED BY DEFAULT AS IDENTITY,
    kode_icd     varchar(10),
    nama         varchar(250),
    id_jenis_icd integer NOT NULL,
    create_user  varchar(20),
    create_date  timestamp(3),
    update_user  varchar(20),
    update_date  timestamp(3),
    CONSTRAINT reficd_pkey PRIMARY KEY (id)
);

-- Additions to the lab layout; the lab data satisfies them (every code is
-- unique and every type exists).
ALTER TABLE reficd
    ADD CONSTRAINT reficd_kode_icd_key UNIQUE (kode_icd),
    ADD CONSTRAINT fk_reficd_jenis FOREIGN KEY (id_jenis_icd) REFERENCES refjenisicd (id);

-- Server-side search over ~18.5k codes (pg_trgm comes from 024).
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE INDEX IF NOT EXISTS reficd_nama_trgm ON reficd USING gin (nama gin_trgm_ops);
CREATE INDEX IF NOT EXISTS reficd_kode_trgm ON reficd USING gin (kode_icd gin_trgm_ops);
CREATE INDEX IF NOT EXISTS reficd_nama_idx ON reficd (nama);
CREATE INDEX IF NOT EXISTS reficd_jenis_idx ON reficd (id_jenis_icd);
