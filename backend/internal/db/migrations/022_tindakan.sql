-- Master Data Klinik > Tindakan: medical procedures (reftindakan), their type
-- (refjenistindakan) and prices per branch (reftindakandetail). Same columns,
-- types and primary keys as in the legacy "lab" database. Data is loaded with
-- scripts/import-lab-tindakan.sh, not seeded here.

CREATE TABLE IF NOT EXISTS refjenistindakan (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    info varchar(50)
);

--   hbeli, hjual, hjual_jamkes  default purchase, sale and health-insurance (jamkes) price
--   isactive                    1 = active procedure
--   isedit, sts_ctk_krtu        flags from the legacy app (1/0)
CREATE TABLE IF NOT EXISTS reftindakan (
    id           integer GENERATED BY DEFAULT AS IDENTITY,
    nama         varchar(100),
    id_jenis     integer,
    hbeli        double precision,
    hjual        double precision,
    create_user  varchar(20),
    create_date  timestamp(3),
    update_user  varchar(20),
    update_date  timestamp(3),
    sts_ctk_krtu integer,
    isedit       integer,
    isactive     integer,
    hjual_jamkes double precision,
    CONSTRAINT reftindakan_pkey PRIMARY KEY (id)
);
-- No FK on id_jenis: one procedure in lab points to a type that no longer exists.

--   cabang                      refbranch.kode
--   hbeli, hjual, hjual_jamkes  prices of the procedure at this branch
--   isactive                    1 = offered at this branch
CREATE TABLE IF NOT EXISTS reftindakandetail (
    id           integer GENERATED BY DEFAULT AS IDENTITY,
    id_tindakan  integer,
    cabang       varchar(3),
    hbeli        double precision,
    hjual        double precision,
    hjual_jamkes double precision,
    isactive     integer NOT NULL DEFAULT 1,
    CONSTRAINT reftindakandetail_pkey PRIMARY KEY (id)
);

-- Additions to the lab layout: one price row per procedure and branch (lab has
-- three identical duplicates, imported once), and no unknown procedure or branch.
ALTER TABLE reftindakandetail
    ADD CONSTRAINT reftindakandetail_tindakan_cabang_key UNIQUE (id_tindakan, cabang),
    ADD CONSTRAINT fk_reftindakandetail_tindakan FOREIGN KEY (id_tindakan) REFERENCES reftindakan (id) ON DELETE CASCADE,
    ADD CONSTRAINT fk_reftindakandetail_cabang FOREIGN KEY (cabang) REFERENCES refbranch (kode);
CREATE INDEX IF NOT EXISTS reftindakandetail_cabang_idx ON reftindakandetail (cabang);
