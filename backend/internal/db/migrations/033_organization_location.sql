-- Master Data Satu Sehat > Organisasi & Lokasi: per branch and poli
-- (refjenisrawat), the SATUSEHAT Organization and Location the clinic
-- registered, with their names and SATUSEHAT IDs. Same columns, types and
-- primary key as in the legacy "lab" database. Data is loaded with
-- scripts/import-lab-organisasi-lokasi.sh.
--
--   jenisrawatid       refjenisrawat id (the poli). No foreign key on purpose:
--                      scripts/import-lab-pendaftaran.sh truncates refjenisrawat
--                      with CASCADE, which would wipe this table.
--   organizationkeyid  SATUSEHAT Organization id (UUID), NULL until registered
--   locationkeyid      SATUSEHAT Location id (UUID), NULL until registered
--
-- Checked against lab: every branch code exists in refbranch and each
-- (cabang, jenisrawatid) pair appears once.
CREATE TABLE IF NOT EXISTS reforganizationlocation (
    id                integer GENERATED BY DEFAULT AS IDENTITY,
    cabang            varchar(3),
    jenisrawatid      integer,
    organizationname  varchar(50),
    locationname      varchar(50),
    organizationkeyid text,
    locationkeyid     text,
    updatedby         varchar(30),
    updatedat         timestamp(3) without time zone,
    CONSTRAINT reforganizationlocation_pkey PRIMARY KEY (id),
    CONSTRAINT uq_reforganizationlocation_poli UNIQUE (cabang, jenisrawatid),
    CONSTRAINT fk_reforganizationlocation_cabang FOREIGN KEY (cabang) REFERENCES refbranch (kode)
);
