-- Master Data Klinik > Dokter: doctors (refmdokter), their type
-- (refjenisdokter), the branches they practise at (refmdokterauth) and the
-- procedures they may perform (trxtindakan -> reftindakan). Same columns, types
-- and primary keys as in the legacy "lab" database. Data is loaded with
-- scripts/import-lab-dokter.sh; 027_dokter_keys.sql adds the keys afterwards.

CREATE TABLE IF NOT EXISTS refjenisdokter (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    info varchar(30)
);

--   id_jenisdok     refjenisdokter
--   id_gender, id_agama, id_goldarah, id_statuskwn  lookups shared with refmpasien
--   status          1 = Active, 2 = Non Active
--   id_internal, cabang, oldid  legacy fields, kept as they are
--   ihs_*, notesatusehat        Satu Sehat (IHS) practitioner link
CREATE TABLE IF NOT EXISTS refmdokter (
    id            integer GENERATED BY DEFAULT AS IDENTITY,
    nama          varchar(30) NOT NULL,
    id_jenisdok   integer,
    tgl_masuk     date,
    tmpt_lahir    varchar(25),
    tgl_lahir     date,
    alamat        varchar(100),
    telp          varchar(20),
    hp            varchar(20),
    pendidikan    varchar(30),
    spesialis     varchar(30),
    id_gender     integer,
    id_agama      integer,
    id_goldarah   integer,
    id_statuskwn  integer,
    create_user   varchar(20),
    create_date   timestamp(3),
    update_user   varchar(20),
    update_date   timestamp(3),
    id_internal   integer,
    cabang        varchar(10),
    oldid         integer,
    status        integer,
    nik           varchar(20),
    ihs_id        varchar(30),
    ihs_name      varchar(100),
    ihs_status    varchar(20),
    notesatusehat varchar(1),
    CONSTRAINT refmdokter_pkey PRIMARY KEY (id)
);

-- Branches where a doctor practises ("Cabang Praktek").
CREATE TABLE IF NOT EXISTS refmdokterauth (
    id       integer GENERATED BY DEFAULT AS IDENTITY,
    dokterid integer,
    cabang   varchar(10),
    CONSTRAINT refmdokterauth_pkey PRIMARY KEY (id)
);

-- Procedures a doctor may perform ("Tindakan Dokter").
CREATE TABLE IF NOT EXISTS trxtindakan (
    id          integer GENERATED BY DEFAULT AS IDENTITY,
    id_dokter   integer,
    id_tindakan integer,
    CONSTRAINT trxtindakan_pkey PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS refmdokterauth_dokterid_idx ON refmdokterauth (dokterid);
CREATE INDEX IF NOT EXISTS trxtindakan_id_dokter_idx ON trxtindakan (id_dokter);
