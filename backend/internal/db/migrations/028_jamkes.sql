-- Master Data Klinik > Jaminan Kesehatan: health insurers (refjaminankesehatan,
-- created in 024), their type, their cooperation-agreement (PKS) terms and a
-- numbered list of items per insurer. Same columns and types as in the legacy
-- "lab" database. Data is loaded with scripts/import-lab-jamkes.sh.
--
--   refjaminankesehatan.jamkestype    refjaminankesehatantype (PT, CV, Non PT CV, ...)
--   refjaminankesehatan.isactive      1 = Active, 2 = Non Active
--   refjaminankesehatan.status_limit  1 = Limit ("limit" is the amount), 2 = No Limit

CREATE TABLE IF NOT EXISTS refjaminankesehatantype (
    id   integer NOT NULL,
    nama varchar(20),
    CONSTRAINT refjaminankesehatantype_pkey PRIMARY KEY (id)
);

-- The PKS term names (Masa berlaku PKS, Tarif, Biaya Adm, ...). In lab this
-- table has no primary key; the app adds one so terms can reference it.
CREATE TABLE IF NOT EXISTS refjaminankesehatan_pksmaster (
    id          integer,
    description varchar(30)
);

--   detailid  refjaminankesehatan_pksmaster.id (which term)
--   value     the term's text for this insurer
--   flag      1 = shown
CREATE TABLE IF NOT EXISTS refjaminankesehatan_detail (
    id       integer GENERATED BY DEFAULT AS IDENTITY,
    jamkesid integer,
    detailid integer,
    value    text,
    flag     integer,
    CONSTRAINT refjaminankesehatan_detail_pkey PRIMARY KEY (id)
);

--   detailid  the item's number in the insurer's list (1, 2, 3, ...)
--   value     the item text (in lab: exclusions such as "Penyakit akibat alkohol dan narkoba")
--   flag      1 = shown
CREATE TABLE IF NOT EXISTS refjaminankesehatan_detail_item (
    id       integer GENERATED BY DEFAULT AS IDENTITY,
    jamkesid integer,
    detailid integer,
    value    text,
    flag     integer,
    CONSTRAINT refjaminankesehatan_detail_item_pkey PRIMARY KEY (id)
);

