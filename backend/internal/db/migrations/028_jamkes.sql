-- Additions to the lab layout; the lab data satisfies all of them.
ALTER TABLE refjaminankesehatan_pksmaster
    ALTER COLUMN id SET NOT NULL,
    ADD CONSTRAINT refjaminankesehatan_pksmaster_pkey PRIMARY KEY (id);
ALTER TABLE refjaminankesehatan
    ADD CONSTRAINT fk_refjaminankesehatan_type FOREIGN KEY (jamkestype) REFERENCES refjaminankesehatantype (id);
ALTER TABLE refjaminankesehatan_detail
    ADD CONSTRAINT refjaminankesehatan_detail_jamkes_term_key UNIQUE (jamkesid, detailid),
    ADD CONSTRAINT fk_refjaminankesehatan_detail_jamkes FOREIGN KEY (jamkesid) REFERENCES refjaminankesehatan (id) ON DELETE CASCADE,
    ADD CONSTRAINT fk_refjaminankesehatan_detail_term FOREIGN KEY (detailid) REFERENCES refjaminankesehatan_pksmaster (id);
ALTER TABLE refjaminankesehatan_detail_item
    ADD CONSTRAINT fk_refjaminankesehatan_detail_item_jamkes FOREIGN KEY (jamkesid) REFERENCES refjaminankesehatan (id) ON DELETE CASCADE;
CREATE INDEX IF NOT EXISTS refjaminankesehatan_detail_item_jamkes_idx ON refjaminankesehatan_detail_item (jamkesid);
