-- The lines of a treatment sale (trxjual): drugs, procedures, supporting
-- examinations and diagnoses. Same columns, types and primary keys as in the
-- legacy "lab" database; loaded with scripts/import-lab-pengobatan-detail.sh,
-- which skips the 104 lab lines whose sale no longer exists.
--
-- Each line belongs to its sale (deleted with it). There are no foreign keys
-- to drugs, procedures, examinations or ICD codes, because their re-imports
-- truncate those tables; lines keep the price at the time of sale.

--   hjual, byk  sale price and quantity; hp  cost price at the branch
--   ppn         10% of hjual x byk for taxable drugs
--   dosis       how to take it, e.g. 3 x 1
CREATE TABLE IF NOT EXISTS trxjualobat (
    id      integer GENERATED BY DEFAULT AS IDENTITY,
    id_jual integer,
    id_obat integer,
    hjual   double precision,
    byk     double precision,
    hp      double precision,
    dosis   varchar(100),
    ppn     double precision,
    CONSTRAINT pk_trxjualobat PRIMARY KEY (id),
    CONSTRAINT fk_trxjualobat_jual FOREIGN KEY (id_jual) REFERENCES trxjual (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS trxjualobat_id_jual_idx ON trxjualobat (id_jual);

--   id_tndk  reftindakan; id_dok  the doctor (the sale's Dokter PJ)
CREATE TABLE IF NOT EXISTS trxjualtindakan (
    id      integer GENERATED BY DEFAULT AS IDENTITY,
    id_jual integer,
    id_tndk integer,
    hjual   double precision,
    byk     double precision,
    id_dok  integer,
    CONSTRAINT pk_trxjualtindakan PRIMARY KEY (id),
    CONSTRAINT fk_trxjualtindakan_jual FOREIGN KEY (id_jual) REFERENCES trxjual (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS trxjualtindakan_id_jual_idx ON trxjualtindakan (id_jual);

--   id_pnjng  refpenunjang
CREATE TABLE IF NOT EXISTS trxjualpnjng (
    id       integer GENERATED BY DEFAULT AS IDENTITY,
    id_jual  integer,
    id_pnjng integer,
    hjual    double precision,
    byk      double precision,
    CONSTRAINT pk_trxjualpnjng PRIMARY KEY (id),
    CONSTRAINT fk_trxjualpnjng_jual FOREIGN KEY (id_jual) REFERENCES trxjual (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS trxjualpnjng_id_jual_idx ON trxjualpnjng (id_jual);

--   icd_id  reficd
CREATE TABLE IF NOT EXISTS trxjualdiagnosa (
    id      integer GENERATED BY DEFAULT AS IDENTITY,
    id_jual integer,
    icd_id  integer,
    CONSTRAINT trxjualdiagnosa_pkey PRIMARY KEY (id),
    CONSTRAINT fk_trxjualdiagnosa_jual FOREIGN KEY (id_jual) REFERENCES trxjual (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS trxjualdiagnosa_id_jual_idx ON trxjualdiagnosa (id_jual);
